#!/usr/bin/env python3
"""Export only checksum-verified frozen GPU TESTED CoDiVE-KC results.

Training, validation and incomplete final-test records are never reported as
completed experiments. The lock covers collection and all four atomic exports.
"""
from __future__ import annotations

import argparse
import csv
import fcntl
import io
import json
import math
import os
import re
import statistics
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import torch

from codive.io import fingerprint, now, read_json, sha256_file, write_json

SUBJECTS = ("Math", "Biology")
VARIANTS = ("concept_evidence",)  # text_control baselines are the v7 runs (same text pipeline)
SEEDS = (200408, 200409)
REQUIRED_ARTIFACTS = ("best.pt", "frozen.json", "test_predictions.pt", "test_metrics.json", "val_calibration.json")
METRIC_PROTOCOL = dict(primary="Weighted-F1 (%)", scale="percentage", decimal_places=2,
                       accuracy="ACC (%)", supplementary="Macro-F1 (%)", split="test",
                       aggregation="Arithmetic mean across completed, verified seeds; sample std (0 for a single seed)")


def _finite_metric(metrics: dict[str, Any], key: str) -> float:
    value = metrics.get(key)
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or not 0 <= value <= 1:
        raise ValueError(f"Invalid {key}; expected finite raw value in [0, 1]")
    return float(value)


def _prediction_metrics(payload: dict[str, Any]) -> dict[str, float | int]:
    targets = torch.as_tensor(payload["targets"], dtype=torch.long).cpu()
    if "predictions" in payload:
        predictions = torch.as_tensor(payload["predictions"], dtype=torch.long).cpu()
    elif "logits" in payload:
        values = torch.as_tensor(payload["logits"]).cpu()
        if values.ndim != 2 or not bool(torch.isfinite(values).all()):
            raise ValueError("Invalid final test logits")
        predictions = values.argmax(-1)
    else:
        raise ValueError("Final test predictions are missing")
    if targets.ndim != 1 or predictions.shape != targets.shape or targets.numel() == 0:
        raise ValueError("Test target/prediction shapes must be nonempty matching vectors")
    if targets.min().item() < 0 or predictions.min().item() < 0:
        raise ValueError("Negative target/prediction label")
    classes = int(torch.maximum(targets.max(), predictions.max()).item()) + 1
    if "logits" in payload:
        values = torch.as_tensor(payload["logits"])
        if values.ndim != 2 or values.shape[0] != targets.numel() or values.shape[1] < classes:
            raise ValueError("Invalid class dimensions for final test logits")
        if not bool(torch.isfinite(values).all()):
            raise ValueError("Nonfinite final test logits")
        classes = values.shape[1]
    support = torch.bincount(targets, minlength=classes).double()
    predicted = torch.bincount(predictions, minlength=classes).double()
    correct = torch.bincount(targets[targets == predictions], minlength=classes).double()
    denominator = support + predicted
    f1 = torch.where(denominator > 0, 2 * correct / denominator.clamp_min(1), torch.zeros_like(correct))
    return dict(n=targets.numel(), accuracy=(targets == predictions).double().mean().item(),
                weighted_f1=(f1 * support).sum().item() / targets.numel(),
                macro_f1=f1.mean().item())


def verify_run(run_dir: str | Path, dataset: str, variant: str, seed: int) -> dict[str, Any] | None:
    """Return one verified TESTED row, or None for unfinished experiments.

    A falsely declared TESTED run raises ValueError. No model execution occurs;
    predictions are already generated by the reservation-authorized GPU worker.
    """
    run_dir = Path(run_dir)
    completion_path = run_dir / "complete.json"
    if not completion_path.is_file():
        return None
    completion = read_json(completion_path)
    if completion.get("status") != "TESTED":
        return None
    signature = completion.get("signature")
    if not isinstance(signature, str) or not signature:
        raise ValueError("Missing final completion signature")
    artifacts = completion.get("artifacts")
    if not isinstance(artifacts, dict) or any(name not in artifacts for name in REQUIRED_ARTIFACTS):
        raise ValueError("TESTED completion is missing a required artifact checksum")
    verified = {}
    for name, expected in artifacts.items():
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts or not re.fullmatch(r"[a-f0-9]{64}", str(expected)):
            raise ValueError(f"Invalid completed artifact record: {name}")
        path = run_dir / relative
        if not path.is_file():
            raise ValueError(f"TESTED artifact is missing: {name}")
        actual = sha256_file(path)
        if actual != expected:
            raise ValueError(f"TESTED artifact checksum mismatch: {name}")
        verified[name] = actual
    frozen = read_json(run_dir / "frozen.json")
    if frozen.get("frozen") is not True or frozen.get("signature") != signature:
        raise ValueError("Final model is not frozen with the completed signature")
    if frozen.get("dataset", frozen.get("subject")) != dataset or frozen.get("seed") != seed:
        raise ValueError("Frozen dataset/seed mismatch")
    if frozen.get("selection_split") != "val_select":
        raise ValueError("Frozen model must be selected only on val_select")
    if frozen.get("checkpoint_sha256") != verified["best.pt"]:
        raise ValueError("Frozen checkpoint checksum differs from completed best.pt")
    checkpoint_path = frozen.get("checkpoint_path", frozen.get("checkpoint"))
    if checkpoint_path is None or Path(checkpoint_path).resolve() != (run_dir / "best.pt").resolve():
        raise ValueError("Frozen checkpoint path differs from completed best.pt")
    if frozen.get("variant", variant) != variant:
        raise ValueError("Frozen method variant mismatch")
    metrics = read_json(run_dir / "test_metrics.json")
    expected_identity = dict(dataset=dataset, variant=variant, seed=seed, split="test")
    if any(metrics.get(key) != value for key, value in expected_identity.items()):
        raise ValueError("Final test metric dataset/variant/seed/split mismatch")
    if metrics.get("signature", signature) != signature:
        raise ValueError("Metric signature differs from final completion")
    if metrics.get("frozen_checkpoint_sha256", verified["best.pt"]) != verified["best.pt"]:
        raise ValueError("Metric checkpoint differs from final frozen checkpoint")
    accuracy = _finite_metric(metrics, "accuracy")
    weighted_f1 = _finite_metric(metrics, "weighted_f1")
    macro_f1 = _finite_metric(metrics, "macro_f1")
    if isinstance(metrics.get("n"), bool) or not isinstance(metrics.get("n"), int) or metrics["n"] <= 0:
        raise ValueError("Invalid final test sample count")
    payload = torch.load(run_dir / "test_predictions.pt", map_location="cpu", weights_only=False)
    if not isinstance(payload, dict) or payload.get("signature") != signature:
        raise ValueError("Final prediction signature differs from completion")
    recomputed = _prediction_metrics(payload)
    if metrics["n"] != recomputed["n"]:
        raise ValueError("Final test target count differs from reported sample count")
    for key, actual in (("accuracy", accuracy), ("weighted_f1", weighted_f1)):
        if not math.isclose(actual, recomputed[key], rel_tol=0, abs_tol=1e-7):
            raise ValueError(f"Saved final predictions disagree with reported {key}")
    for key in ("source_rows", "row_ids"):
        if key in payload and len(payload[key]) != metrics["n"]:
            raise ValueError(f"Prediction {key} count differs from final test sample count")
    calibration = read_json(run_dir / "val_calibration.json")
    if calibration.get("signature", signature) != signature:
        raise ValueError("Calibration signature differs from final completion")
    return dict(**expected_identity, status="TESTED", n=metrics["n"],
                accuracy=accuracy, weighted_f1=weighted_f1, macro_f1=macro_f1,
                **{"ACC (%)": round(100 * accuracy, 2), "Weighted-F1 (%)": round(100 * weighted_f1, 2),
                   "Macro-F1 (%)": round(100 * macro_f1, 2)},
                signature=signature, checkpoint_sha256=verified["best.pt"],
                complete_sha256=sha256_file(completion_path), verified_artifacts=verified,
                run_dir=str(run_dir.resolve()), fix_count=metrics.get("fix_count"), harm_count=metrics.get("harm_count"),
                device=metrics.get("device"))


def collect_runs(root: str | Path = ROOT) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
    root = Path(root)
    rows, errors, skipped = [], [], []
    for dataset in SUBJECTS:
        for variant in VARIANTS:
            for seed in SEEDS:
                run_dir = root / "runs" / dataset / variant / f"seed{seed}"
                identity = dict(dataset=dataset, variant=variant, seed=seed, run_dir=str(run_dir))
                try:
                    row = verify_run(run_dir, dataset, variant, seed)
                    if row is None:
                        skipped.append(dict(**identity, reason="No final TESTED completion record"))
                    else:
                        rows.append(row)
                except (OSError, ValueError, KeyError, TypeError, RuntimeError, EOFError) as exc:
                    errors.append(dict(**identity, error=f"{type(exc).__name__}: {exc}"))
    return rows, errors, skipped


def summarize(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    summary = []
    for dataset in SUBJECTS:
        for variant in VARIANTS:
            group = [row for row in rows if row["dataset"] == dataset and row["variant"] == variant]
            if not group:
                continue
            values = dict(dataset=dataset, variant=variant, seeds=len(group), seed_values=sorted(row["seed"] for row in group), split="test")
            for source, destination in (("accuracy", "ACC (%)"), ("weighted_f1", "Weighted-F1 (%)"), ("macro_f1", "Macro-F1 (%)")):
                series = [100 * row[source] for row in group]
                values[destination] = round(statistics.mean(series), 2)
                values[destination + " std"] = round(statistics.stdev(series) if len(series) > 1 else 0.0, 2)
            summary.append(values)
    return summary


def _atomic_csv(path: Path, rows: list[dict[str, Any]], fields: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    output = io.StringIO(newline="")
    writer = csv.DictWriter(output, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()
    for row in rows:
        formatted = dict(row)
        for field in fields:
            if field.startswith(("ACC (%)", "Weighted-F1 (%)", "Macro-F1 (%)")) and field in formatted:
                formatted[field] = f"{formatted[field]:.2f}"
        writer.writerow(formatted)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="") as handle:
            handle.write(output.getvalue())
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def export_results(root: str | Path = ROOT) -> dict[str, Any]:
    root = Path(root)
    results = root / "results"
    results.mkdir(parents=True, exist_ok=True)
    with (results / ".export.lock").open("a+") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        rows, errors, skipped = collect_runs(root)
        grouped = summarize(rows)
        shared = dict(generated_at=now(), metric_protocol=METRIC_PROTOCOL,
                      verified_runs=len(rows), invalid_tested_runs=errors, unfinished_runs=skipped,
                      collection_fingerprint=fingerprint(rows))
        write_json(results / "per_seed.json", dict(**shared, runs=rows))
        write_json(results / "summary.json", dict(**shared, summary=grouped))
        _atomic_csv(results / "per_seed.csv", rows,
                    ["dataset", "variant", "seed", "split", "status", "n", "ACC (%)", "Weighted-F1 (%)", "Macro-F1 (%)", "fix_count", "harm_count", "checkpoint_sha256", "run_dir"])
        _atomic_csv(results / "summary.csv", grouped,
                    ["dataset", "variant", "seeds", "split", "ACC (%)", "Weighted-F1 (%)", "Macro-F1 (%)", "ACC (%) std", "Weighted-F1 (%) std", "Macro-F1 (%) std"])
        return dict(verified_runs=len(rows), invalid_tested_runs=errors, unfinished_runs=len(skipped),
                    results_dir=str(results.resolve()), collection_fingerprint=shared["collection_fingerprint"])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    result = export_results(args.root)
    print(json.dumps(result, ensure_ascii=False), flush=True)
    return 2 if result["invalid_tested_runs"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
